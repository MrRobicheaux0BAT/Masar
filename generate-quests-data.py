def q(
    id: str,
    name: str,
    category_id: str,
    order: int,
    how_to_start: str,
    description: str,
    *,
    location: str | None = None,
    alternatives: list[str] | None = None,
    can_fail: str | None = None,
    exclusive_group: str | None = None,
    note: str | None = None,
    radiant: bool | None = None,
) -> dict:
    quest: dict = {
        "id": id,
        "name": name,
        "categoryId": category_id,
        "order": order,
        "howToStart": how_to_start,
        "description": description,
    }
    if location is not None:
        quest["location"] = location
    if alternatives is not None:
        quest["alternatives"] = alternatives
    if can_fail is not None:
        quest["canFail"] = can_fail
    if exclusive_group is not None:
        quest["exclusiveGroup"] = exclusive_group
    if note is not None:
        quest["note"] = note
    if radiant is not None:
        quest["radiant"] = radiant
    return quest


