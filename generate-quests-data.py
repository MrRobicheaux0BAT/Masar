def validate(data: dict) -> None:
    cat_ids = [c["id"] for c in data["categories"]]
    required = [
        "main", "companions", "college", "thieves_guild", "dark_brotherhood",
        "imperial", "stormcloaks", "daedric", "bards", "dawnguard", "dragonborn",
        "hearthfire", "side_whiterun", "side_riften", "side_solitude", "side_windhelm",
        "side_markarth", "side_morthal", "side_falkreath", "side_dawnstar",
        "side_winterhold", "side_solstheim", "misc_world",
    ]
    if cat_ids != required:
        missing = [c for c in required if c not in cat_ids]
        extra = [c for c in cat_ids if c not in required]
        order_ok = cat_ids == required
        raise SystemExit(f"Category list mismatch. missing={missing} extra={extra} order_ok={order_ok}")

    quest_ids = [x["id"] for x in data["quests"]]
    if len(quest_ids) != len(set(quest_ids)):
        seen = set()
        dupes = []
        for i in quest_ids:
            if i in seen:
                dupes.append(i)
            seen.add(i)
        raise SystemExit(f"Duplicate quest ids: {dupes}")

    for quest in data["quests"]:
        if quest["categoryId"] not in cat_ids:
            raise SystemExit(f"Quest {quest['id']} has unknown category {quest['categoryId']}")


def main() -> None:
    data = {"categories": CATEGORIES, "quests": QUESTS}
    validate(data)

    json_path = ROOT / "quests-data.json"
    js_path = ROOT / "quests-data.js"

    json_text = json.dumps(data, indent=2, ensure_ascii=False)
    json_path.write_text(json_text + "\n", encoding="utf-8")
    js_path.write_text(
        "window.QUESTS_DATA = " + json_text + ";\n",
        encoding="utf-8",
    )

    # Stats
    from collections import Counter

    counts = Counter(q["categoryId"] for q in QUESTS)
    thin = [cid for cid in cat_ids_ordered() if counts[cid] < 2]

    print(f"categories: {len(CATEGORIES)}")
    print(f"quests: {len(QUESTS)}")
    print(f"categories_with_fewer_than_2_quests: {thin if thin else 'none'}")
    for cid in cat_ids_ordered():
        print(f"  {cid}: {counts[cid]}")


def cat_ids_ordered() -> list[str]:
    return [c["id"] for c in CATEGORIES]


if __name__ == "__main__":
    main()
